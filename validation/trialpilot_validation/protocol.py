"""`tpv protocol`: OQ test protocol listing the tests per requirement.

The protocol body is deterministic (no timestamps, repo-relative ids) so regenerating an unchanged
protocol gives the same sha256 and keeps its approval. The approval record id carries the content
hash (`OQ-TP-001-<sha8>`), so every changed version needs its own approval.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from . import identity
from .context import Ctx, TpvError, md_escape, read_json, sha256_file, utc_now, write_json, write_text
from .runner import load_suite_tests, run_suite, scan_e2e

MIN_TESTS = {"H": 2, "M": 1, "L": 1}


def collect(ctx: Ctx) -> dict[str, Any]:
    """Collect every suite (no execution) + scan Playwright specs; save under out/collect/."""
    outdir = ctx.out / "collect"
    summaries = [run_suite(ctx, s, outdir, "collect") for s in ctx.config["suites"]]
    tests, errors = load_suite_tests(outdir, summaries)
    tests += scan_e2e(ctx)
    data = {"collected_at": utc_now(), "suites": summaries, "tests": tests,
            "collection_errors": errors}
    write_json(outdir / "collection.json", data)
    return data


def latest_collection(ctx: Ctx) -> dict[str, Any] | None:
    p = ctx.out / "collect" / "collection.json"
    return read_json(p) if p.exists() else None


def plan_tests(requirements: list[dict[str, Any]], tests: list[dict[str, Any]]) -> dict[str, Any]:
    ids = {r["id"] for r in requirements}
    per_req: dict[str, list[str]] = {r["id"]: [] for r in requirements}
    unknown: dict[str, list[str]] = {}
    untagged: list[str] = []
    for t in sorted(tests, key=lambda t: t["id"]):
        if not t.get("reqs"):
            untagged.append(t["id"])
        for rid in t.get("reqs", []):
            if rid in ids:
                per_req[rid].append(t["id"])
            else:
                unknown.setdefault(rid, []).append(t["id"])
    return {"per_req": per_req, "unknown_refs": unknown, "untagged": untagged}


def render(ctx: Ctx, requirements: list[dict[str, Any]], collection: dict[str, Any]) -> tuple[
        str, dict[str, Any]]:
    plan = plan_tests(requirements, collection["tests"])
    kinds = {t["id"]: t.get("kind", "pytest") for t in collection["tests"]}
    urs_sha = sha256_file(ctx.vdir / "requirements.yaml")
    pid = ctx.config["protocol_id"]
    lines = [
        f"# OQ Test Protocol {pid}",
        "",
        f"System: **{ctx.config['system']}** · Requirements: `validation/requirements.yaml` "
        f"(sha256 `{urs_sha[:16]}…`) · Procedure: SOP CSV-001 (fictional)",
        "",
        "This protocol was generated by `tpv protocol` from the requirements and the test suites. "
        "It must be **reviewed and then approved by QA before it is executed** (SOP CSV-001 §5.1); "
        "`tpv execute` refuses to run an unapproved or changed protocol.",
        "",
        "## 1. Objective",
        "Verify that TrialPilot meets each user requirement (operational qualification) by running "
        "the automated tests listed below and recording their results as signed evidence.",
        "",
        "## 2. Prerequisites",
        "- Each Python package runs in its own virtual environment (`uv run --project <package>`).",
        "- `DEMO_OFFLINE=1` (no network access during testing).",
        "- Playwright specs run only when the web app and browsers are installed (`tpv execute --e2e`);"
        " otherwise they are reported as *not run*.",
        "",
        "## 3. Acceptance criteria",
        "- A requirement **passes** when every listed test passes and at least one ran.",
        "- Any failed or erroring test is a deviation and is reported in the summary report.",
        "- SOP minimum test depth: H ≥ 2 tests (incl. a negative test), M ≥ 1, L ≥ 1 or justification.",
        "- Requirements without any test cannot pass and are reported as gaps.",
        "",
        "## 4. Test cases per requirement",
        "",
    ]
    gaps: list[str] = []
    for r in requirements:
        rid = r["id"]
        tests = plan["per_req"][rid]
        gxp = "GxP" if r["gxp"] else "non-GxP"
        lines.append(f"### {rid} — risk {r['risk']}, {gxp}")
        lines.append("")
        lines.append(" ".join(str(r["text"]).split()))
        lines.append("")
        if not tests:
            gaps.append(rid)
            lines.append("**NO TEST** — this requirement cannot be verified by this protocol (gap).")
        else:
            lines.append("| # | Test | Type | Expected result |")
            lines.append("|---|---|---|---|")
            for i, tid in enumerate(tests, 1):
                lines.append(f"| {i} | `{md_escape(tid)}` | {kinds.get(tid, 'pytest')} | passes |")
            if len(tests) < MIN_TESTS[r["risk"]]:
                lines.append("")
                lines.append(f"*Below SOP minimum depth for risk {r['risk']} "
                             f"({len(tests)} of {MIN_TESTS[r['risk']]} tests).*")
        lines.append("")
    lines += ["## 5. Gaps and inventory", ""]
    lines.append(f"- Requirements with no test: **{len(gaps)}**"
                 + (f" ({', '.join(gaps)})" if gaps else ""))
    unknown = plan["unknown_refs"]
    lines.append(f"- Tests referencing unknown requirement ids: **{sum(map(len, unknown.values()))}**"
                 + (f" ({', '.join(sorted(unknown))})" if unknown else ""))
    lines.append(f"- Tests with no requirement id: **{len(plan['untagged'])}** (Appendix A)")
    err_ids = sorted({e["id"] for e in collection.get("collection_errors", [])})
    lines.append(f"- Collection errors: **{len(err_ids)}**" + (
        "".join(f"\n  - `{md_escape(e)}`" for e in err_ids) if err_ids else ""))
    not_present = [s["name"] for s in collection.get("suites", [])
                   if s.get("status") == "not_present"]
    if not_present:
        lines.append(f"- Suites not present: {', '.join(not_present)}")
    lines += ["", "## Appendix A — tests without a requirement id", ""]
    lines += [f"- `{md_escape(t)}`" for t in plan["untagged"]] or ["(none)"]
    lines.append("")
    body = "\n".join(lines)
    meta = {"protocol_id": pid, "requirements_sha256": urs_sha, "planned": plan["per_req"],
            "unknown_refs": unknown, "untagged": plan["untagged"], "gaps": gaps,
            "collection_errors": err_ids}
    return body, meta


def generate(ctx: Ctx, *, collection: dict[str, Any] | None = None,
             register: bool = True) -> dict[str, Any]:
    requirements = ctx.requirements()
    collection = collection or collect(ctx)
    body, meta = render(ctx, requirements, collection)
    from .context import sha256_text

    digest = sha256_text(body)
    record_id = f"{ctx.config['protocol_id']}-{digest[:8]}"
    pdir = ctx.out / "protocol"
    path = write_text(pdir / f"{record_id}.md", body)
    if sha256_file(path) != digest:  # pragma: no cover - would mean newline translation
        raise TpvError("protocol hash mismatch after writing")
    meta.update(record_id=record_id, sha256=digest, path=ctx.rel(path), generated_at=utc_now())
    write_json(pdir / f"{record_id}.json", meta)
    write_json(pdir / "current.json", {"record_id": record_id, "sha256": digest,
                                       "path": ctx.rel(path), "generated_at": meta["generated_at"]})
    if register:
        c = identity.compliance()
        c.records.register_file("test_protocol", record_id, path)
    return meta


def current(ctx: Ctx) -> dict[str, Any]:
    p = ctx.out / "protocol" / "current.json"
    if not p.exists():
        raise TpvError("No test protocol yet. Run `tpv protocol` first.")
    cur = read_json(p)
    meta_path = ctx.out / "protocol" / f"{cur['record_id']}.json"
    meta = read_json(meta_path) if meta_path.exists() else {}
    return {**meta, **cur, "file": ctx.repo / cur["path"] if not Path(cur["path"]).is_absolute()
            else Path(cur["path"])}


def submit(ctx: Ctx, record_id: str, username: str | None, title: str) -> dict[str, Any]:
    c = identity.compliance()
    user = identity.resolve_user(username)
    st = c.workflow.approval_status("test_protocol", record_id)
    if st["approval_id"] and st["status"] in ("pending", "approved"):
        return {"approval_id": st["approval_id"], "status": st["status"], "created": False}
    try:
        req = c.workflow.create_request("test_protocol", record_id, user.username, title=title,
                                        reason="OQ protocol submitted for review and approval")
    except c.ComplianceError as exc:
        raise TpvError(f"{exc.code}: {exc.message}") from exc
    return {"approval_id": req.id, "status": req.status, "created": True}

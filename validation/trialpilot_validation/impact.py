"""`tpv impact --base <ref> --head <ref>`: change control.

changed files (git diff) → components (`validation/component_map.yaml`) → requirements → tests to
rerun (from the latest collection/execution) → change record draft. The description, justification
and decision are left for humans (marked DRAFT); tpv fills only what it can compute.
"""

from __future__ import annotations

import fnmatch
from typing import Any

import yaml

from . import execute, identity, protocol
from .context import (
    DRAFT_STAMP,
    Ctx,
    TpvError,
    md_escape,
    sha256_text,
    utc_now,
    write_json,
    write_text,
)


def load_map(ctx: Ctx) -> list[dict[str, Any]]:
    path = ctx.vdir / "component_map.yaml"
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    comps = data.get("components") or []
    known = {r["id"] for r in ctx.requirements()}
    for c in comps:
        bad = [r for r in c.get("requirements", []) if r not in known]
        if bad:
            raise TpvError(f"component_map.yaml: {c['id']} cites unknown requirements {bad}")
    return comps


def changed_files(ctx: Ctx, base: str, head: str) -> list[str]:
    if head.upper() == "WORKTREE":
        out = ctx.git("diff", "--name-only", base)
    else:
        out = ctx.git("diff", "--name-only", f"{base}...{head}")
    return sorted({line.strip() for line in out.splitlines() if line.strip()})


def analyse(ctx: Ctx, files: list[str]) -> dict[str, Any]:
    comps = load_map(ctx)
    hits: dict[str, list[str]] = {}
    unmapped: list[str] = []
    for f in files:
        matched = [c["id"] for c in comps
                   if any(fnmatch.fnmatch(f, pat) for pat in c.get("paths", []))]
        if matched:
            hits[f] = matched
        else:
            unmapped.append(f)
    comp_reqs = {c["id"]: c.get("requirements", []) for c in comps}
    reqs = sorted({r for cs in hits.values() for c in cs for r in comp_reqs[c]})
    run = execute.latest_run(ctx)
    tests_src = run["tests"] if run else (protocol.latest_collection(ctx) or {}).get("tests", [])
    tests = sorted({t["id"] for t in tests_src if set(t.get("reqs", [])) & set(reqs)})
    return {"files": files, "components": hits, "unmapped": unmapped, "requirements": reqs,
            "tests_to_rerun": tests, "test_source": "execution" if run else "collection"}


def render(ctx: Ctx, base: str, head: str, a: dict[str, Any]) -> str:
    req_text = {r["id"]: r for r in ctx.requirements()}
    lines = [f"# Change record draft ({base} → {head})", "", DRAFT_STAMP, "",
             "Generated by `tpv impact` (computed from git and `validation/component_map.yaml`). "
             "Sections marked *human* must be completed by the change owner; the record is "
             "approved reviewer → QA before release.", "",
             "## Description of change (*human*)", "", "_To be written by the change owner._", "",
             "## Changed files", ""]
    for f in a["files"]:
        comps = a["components"].get(f)
        lines.append(f"- `{md_escape(f)}` → " + (", ".join(comps) if comps else "**unmapped**"))
    lines += ["", f"Unmapped files: **{len(a['unmapped'])}** (decide impact manually).", "",
              "## Affected requirements", ""]
    for rid in a["requirements"]:
        r = req_text[rid]
        lines.append(f"- **{rid}** ({r['risk']}{', GxP' if r['gxp'] else ''}) — "
                     f"{md_escape(' '.join(str(r['text']).split()))}")
    lines += ["", f"## Tests to rerun ({len(a['tests_to_rerun'])}, from latest "
                  f"{a['test_source']})", ""]
    lines += [f"- `{md_escape(t)}`" for t in a["tests_to_rerun"]] or ["(none mapped)"]
    lines += ["", "## Risk assessment and decision (*human*)", "",
              "_Regression risk, need for full re-execution, and release decision._", ""]
    return "\n".join(lines)


def run_impact(ctx: Ctx, base: str, head: str, *, submit: bool = False,
               submit_as: str | None = None) -> dict[str, Any]:
    """Write the change record draft; with `submit` (or `submit_as`) also submit it for approval
    as `submit_as` or TPV_USER."""
    files = changed_files(ctx, base, head)
    a = analyse(ctx, files)
    body = render(ctx, base, head, a)
    digest = sha256_text(body)
    record_id = f"{ctx.config['change_record_prefix']}-{digest[:8]}"
    d = ctx.out / "change"
    path = write_text(d / f"{record_id}.md", body)
    meta = {"record_id": record_id, "sha256": digest, "base": base, "head": head,
            "generated_at": utc_now(), "path": ctx.rel(path), **a}
    write_json(d / f"{record_id}.json", meta)
    write_json(d / "latest.json", meta)
    if submit or submit_as:
        identity.compliance().records.register_file("change_record", record_id, path)
        r = identity.submit_for_approval("change_record", record_id, submit_as,
                                         title=f"Change record {record_id}",
                                         reason=f"impact {base}..{head}")
        meta.update(approval_id=r["approval_id"], approval_status=r["status"])
    return meta

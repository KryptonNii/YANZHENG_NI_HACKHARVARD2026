import { useEffect, useState } from "react";
import { formatUtc } from "@/app/format";
import { Badge, DraftStamp, EmptyState, ErrorPanel, Spinner } from "@/app/ui";
import { ApiError, validationPackage, type ValidationPackage } from "./api";

function deliverableTone(status: string) {
  const s = status.toLowerCase();
  if (s === "approved" || s === "executed") return "better" as const;
  if (s.includes("draft") || s.includes("await")) return "caution" as const;
  if (s === "missing") return "worse" as const;
  return "neutral" as const;
}

export function ValidationPage() {
  const [pkg, setPkg] = useState<ValidationPackage | null>(null);
  const [missing, setMissing] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = async () => {
    setError(null);
    setMissing(null);
    try {
      setPkg(await validationPackage());
    } catch (err) {
      setPkg(null);
      if (err instanceof ApiError && (err.code === "package_not_built" || err.status === 404)) {
        setMissing(err.message);
        return;
      }
      setError(err instanceof ApiError ? err.message : err instanceof Error ? err.message : String(err));
    }
  };

  useEffect(() => {
    void load();
  }, []);

  const untested = pkg?.trace?.flags?.untested_requirements ?? [];

  return (
    <div className="space-y-4" data-testid="validation-page">
      <header className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Validation package</h1>
          <p className="mt-1 text-sm text-ink-500">
            {pkg?.generated_at ? `Generated ${formatUtc(pkg.generated_at)}` : "Generated by tpv package"}
          </p>
        </div>
        {pkg?.draft_stamp && (
          <span data-testid="draft-stamp">
            <DraftStamp>{pkg.draft_stamp}</DraftStamp>
          </span>
        )}
      </header>

      {error && <ErrorPanel title="Couldn't load the validation package" message={error} onRetry={() => void load()} />}
      {missing && (
        <EmptyState title="No validation package yet">
          {missing}
        </EmptyState>
      )}
      {!pkg && !missing && !error && <Spinner label="Loading validation package" />}

      {pkg && (
        <>
          <section className="card p-4" aria-label="Deliverables">
            <h2 className="card-title mb-3">Deliverables</h2>
            <ul className="divide-y divide-ink-100">
              {pkg.deliverables.map((d) => (
                <li key={d.id} className="flex flex-wrap items-center justify-between gap-2 py-2">
                  <div>
                    <p className="text-sm font-semibold text-ink-900">
                      <span className="mr-2 font-mono text-xs text-ink-400">{d.id}</span>
                      {d.title}
                    </p>
                    {d.sha256 && <p className="font-mono text-[11px] text-ink-400">{d.sha256.slice(0, 16)}…</p>}
                  </div>
                  <div className="flex items-center gap-2">
                    {d.draft_stamp ? <DraftStamp /> : null}
                    <Badge tone={deliverableTone(d.status)}>{d.status}</Badge>
                  </div>
                </li>
              ))}
            </ul>
          </section>

          <section className="card p-4" aria-label="Traceability matrix">
            <h2 className="card-title mb-3">Traceability</h2>
            {untested.length > 0 && (
              <p data-testid="untested-requirements" className="mb-3 rounded-md border border-caution-300 bg-caution-50 px-3 py-2 text-sm font-medium text-caution-900">
                Untested requirements: {untested.join(", ")}
              </p>
            )}
            {pkg.trace?.summary && (
              <p className="mb-3 text-xs text-ink-500">
                {Object.entries(pkg.trace.summary)
                  .map(([k, v]) => `${k} ${v}`)
                  .join(" · ")}
              </p>
            )}
            <div className="max-h-[28rem] overflow-auto">
              <table className="w-full text-left text-sm">
                <thead className="sticky top-0 bg-white text-xs uppercase tracking-wide text-ink-500">
                  <tr>
                    <th className="py-2 pr-3">Requirement</th>
                    <th className="py-2 pr-3">Tests</th>
                    <th className="py-2 pr-3">Result</th>
                    <th className="py-2">Evidence</th>
                  </tr>
                </thead>
                <tbody>
                  {(pkg.trace?.rows ?? []).map((row) => {
                    const gap = untested.includes(row.id) || row.tests.length === 0;
                    return (
                      <tr key={row.id} className={`border-t border-ink-100 ${gap ? "bg-caution-50" : ""}`} data-testid={`trace-${row.id}`}>
                        <td className="py-2 pr-3 align-top">
                          <span className="font-semibold">{row.id}</span>
                          <span className="mt-0.5 block text-xs text-ink-600">{row.text}</span>
                        </td>
                        <td className="py-2 pr-3 align-top text-xs">
                          {row.tests.length === 0 ? "—" : row.tests.map((t) => `${t.id} (${t.outcome ?? "not run"})`).join(", ")}
                        </td>
                        <td className="py-2 pr-3 align-top">
                          <Badge tone={gap ? "caution" : row.result === "pass" ? "better" : row.result === "fail" ? "worse" : "neutral"}>
                            {gap && row.tests.length === 0 ? "no test" : row.result}
                          </Badge>
                        </td>
                        <td className="py-2 align-top font-mono text-[11px] text-ink-500">
                          {row.evidence?.length ? row.evidence.map((e) => e.file).filter(Boolean).join(", ") : "—"}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </section>

          <section className="card p-4" aria-label="Planted defects" data-testid="defect-summary">
            <h2 className="card-title mb-2">Planted defects</h2>
            {pkg.defects ? (
              <>
                <p className="text-sm text-ink-800">
                  Detected {pkg.defects.detected ?? 0} of {pkg.defects.planted ?? pkg.defects.rows?.length ?? 0}.
                </p>
                {pkg.defects.note && <p className="mt-1 text-xs text-ink-500">{pkg.defects.note}</p>}
                <ul className="mt-3 space-y-1 text-sm">
                  {(pkg.defects.rows ?? []).map((row) => (
                    <li key={row.id} className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-xs">{row.id}</span>
                      <Badge tone={row.detected ? "better" : "worse"}>{row.detected ? "detected" : "missed"}</Badge>
                      <span className="text-xs text-ink-500">{(row.stages ?? []).join(", ") || "no stage"}</span>
                    </li>
                  ))}
                </ul>
              </>
            ) : (
              <p className="text-sm text-ink-500">No defect run is included in this package.</p>
            )}
          </section>

          <section className="card p-4" aria-label="Summary report">
            <h2 className="card-title mb-2">Summary report</h2>
            <p className="text-sm text-ink-800">
              QA sign-off: <span className="font-semibold">{pkg.report?.status ?? "not generated"}</span>
            </p>
            {pkg.report?.record_id && <p className="mt-1 font-mono text-xs text-ink-500">{pkg.report.record_id}</p>}
            {pkg.report?.reason && <p className="mt-1 text-sm text-ink-600">{pkg.report.reason}</p>}
          </section>
        </>
      )}
    </div>
  );
}

import { displayText } from "../command/displayText";
import { useTranslation } from "@/app/i18n";
import { localizeCopy } from "@/app/localize";
import { useEffect, useState } from "react";
import { formatUtc } from "@/app/format";
import { Badge, DraftStamp, EmptyState, ErrorPanel, Spinner } from "@/app/ui";
import { ApiError, evidenceManifest, packageFileUrl, validationPackage, type EvidenceFile, type PackageDeliverable, type ValidationPackage } from "./api";

function deliverableStatus(d: PackageDeliverable) {
  if (d.approval && d.status === "approved" && !d.approval.approved) return d.approval.status ?? "approval unconfirmed";
  return d.status;
}

function deliverableTone(status: string) {
  const s = status.toLowerCase();
  if (s === "approved" || s === "executed") return "better" as const;
  if (s.includes("draft") || s.includes("await")) return "caution" as const;
  if (s === "missing") return "worse" as const;
  return "neutral" as const;
}

export function ValidationPage() {
  const t = useTranslation();
  const [pkg, setPkg] = useState<ValidationPackage | null>(null);
  const [missing, setMissing] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = async () => {
    setError(null);
    setMissing(null);
    try {
      setPkg(await validationPackage());
    } catch (err) {
      setPkg(null);
      if (err instanceof ApiError && err.code === "package_not_built") {
        setMissing(err.message);
        return;
      }
      setError(err instanceof ApiError ? err.message : err instanceof Error ? err.message : String(err));
    }
  };

  useEffect(() => {
    void load();
  }, []);

  const untested = pkg?.trace?.flags?.untested_requirements ?? [];

  return (
    <div className="space-y-4" data-testid="validation-page">
      <header className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">{t("Validation package", "验证包")}</h1>
          <p className="mt-1 text-sm text-ink-500">
            {pkg?.generated_at ? t(`Generated ${formatUtc(pkg.generated_at)}`, `生成于 ${formatUtc(pkg.generated_at)}`) : t("Generated by tpv package", "由 tpv package 生成")}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <button type="button" className="btn-secondary" onClick={() => void load()}>{t("Refresh package", "刷新验证包")}</button>
          {pkg?.draft_stamp && (
            <span data-testid="draft-stamp"><DraftStamp>{pkg.draft_stamp}</DraftStamp></span>
          )}
        </div>
      </header>

      {error && <ErrorPanel title={t("Couldn't load the validation package", "无法加载验证包")} message={error} onRetry={() => void load()} />}
      {missing && (
        <EmptyState title={t("No validation package yet", "暂无验证包")}>
          {missing}
        </EmptyState>
      )}
      {!pkg && !missing && !error && <Spinner label={t("Loading validation package", "正在加载验证包")} />}

      {pkg && (
        <>
          <section className="card space-y-2 p-4" aria-label={t("Package provenance", "验证包来源")}>
            <p className="text-sm">{pkg.system ?? t("Validation package", "验证包")}</p>
            <p className="break-all font-mono text-xs text-ink-500">{t("Package commit:", "验证包提交：")} {pkg.git?.commit ?? t("unknown", "未知")}{pkg.git?.dirty ? t(" · uncommitted changes", " · 存在未提交的更改") : ""}</p>
            <div className="flex flex-wrap gap-3 text-sm font-semibold text-accent-700">
              <a href={packageFileUrl("index.html")} target="_blank" rel="noreferrer">{t("Open package HTML", "打开验证包 HTML")}</a>
              <a href={packageFileUrl("package_manifest.json")} download>{t("Download package manifest", "下载验证包清单")}</a>
            </div>
          </section>
          <Execution pkg={pkg} />
          <section className="card p-4" aria-label={t("Deliverables", "交付物")}>
            <h2 className="card-title mb-3">{t("Deliverables", "交付物")}</h2>
            <ul className="divide-y divide-ink-100">
              {pkg.deliverables.map((d) => (
                <li key={d.id} className="flex flex-wrap items-center justify-between gap-2 py-2">
                  <div>
                    <p className="text-sm font-semibold text-ink-900">
                      <span className="mr-2 font-mono text-xs text-ink-400">{d.id}</span>
                      {displayText(d.title)}
                    </p>
                    {d.sha256 && <p title={d.sha256} className="font-mono text-[11px] text-ink-400">Markdown sha256 {d.sha256.slice(0, 16)}…</p>}
                    {d.approval?.reason && <p className="text-xs text-ink-500">{t("Approval:", "审批：")} {displayText(d.approval.status ?? "unknown")} · {d.approval.reason}</p>}
                  </div>
                  <div className="flex items-center gap-2">
                    {d.draft_stamp ? <DraftStamp /> : null}
                    <Badge tone={deliverableTone(deliverableStatus(d))}>{displayText(deliverableStatus(d))}</Badge>
                    {packageFileUrl(d.html) && <a className="text-sm font-semibold text-accent-700" href={packageFileUrl(d.html)} target="_blank" rel="noreferrer" aria-label={t(`Open ${displayText(d.title)} HTML`, `打开 ${displayText(d.title)} HTML`)}>{t("Open HTML", "打开 HTML")}</a>}
                    {packageFileUrl(d.md) && <a className="text-sm font-semibold text-accent-700" href={packageFileUrl(d.md)} download aria-label={t(`Download ${displayText(d.title)} Markdown`, `下载 ${displayText(d.title)} Markdown`)}>{t("Download Markdown", "下载 Markdown")}</a>}
                  </div>
                </li>
              ))}
            </ul>
          </section>

          <section className="card p-4" aria-label={t("Traceability matrix", "可追溯性矩阵")}>
            <h2 className="card-title mb-3">{t("Traceability", "可追溯性")}</h2>
            {untested.length > 0 && (
              <p data-testid="untested-requirements" className="mb-3 rounded-md border border-caution-300 bg-caution-50 px-3 py-2 text-sm font-medium text-caution-900">
                {t("Untested requirements:", "未测试需求：")} {untested.join(", ")}
              </p>
            )}
            {!!pkg.trace?.flags?.failing_requirements?.length && <p data-testid="failing-requirements" className="mb-3 text-sm font-semibold text-worse-900">{t("Failing requirements:", "测试失败需求：")} {pkg.trace.flags.failing_requirements.join(", ")}</p>}
            {pkg.trace?.flags?.tests_without_requirement_count != null && <p className="mb-2 text-xs text-ink-500">{t("Tests without requirement tags:", "未标注需求的测试：")} {pkg.trace.flags.tests_without_requirement_count}</p>}
            {pkg.trace?.summary && (
              <p className="mb-3 text-xs text-ink-500">
                {Object.entries(pkg.trace.summary)
                  .map(([k, v]) => `${displayText(k)} ${v}`)
                  .join(" · ")}
              </p>
            )}
            <div className="max-h-[28rem] overflow-auto">
              <table className="w-full text-left text-sm">
                <thead className="sticky top-0 bg-white text-xs uppercase tracking-wide text-ink-500">
                  <tr>
                    <th className="py-2 pr-3">{t("Requirement", "需求")}</th>
                    <th className="py-2 pr-3">{t("Tests", "测试")}</th>
                    <th className="py-2 pr-3">{t("Result", "结果")}</th>
                    <th className="py-2">{t("Evidence", "证据")}</th>
                  </tr>
                </thead>
                <tbody>
                  {(pkg.trace?.rows ?? []).map((row) => {
                    const gap = untested.includes(row.id) || row.tests.length === 0;
                    return (
                      <tr key={row.id} className={`border-t border-ink-100 ${gap ? "bg-caution-50" : ""}`} data-testid={`trace-${row.id}`}>
                        <td className="py-2 pr-3 align-top">
                          <span className="font-semibold">{row.id}</span>
                          <span className="mt-0.5 block text-xs text-ink-600">{row.text}</span>
                          <span className="text-xs text-ink-500">{row.risk ? t(`Risk ${row.risk}`, `风险 ${displayText(row.risk)}`) : ""}{row.gxp != null ? t(` · GxP ${row.gxp ? "yes" : "no"}`, ` · GxP ${row.gxp ? "是" : "否"}`) : ""}</span>
                        </td>
                        <td className="py-2 pr-3 align-top text-xs">
                          {row.tests.length === 0 ? "—" : <details><summary className="cursor-pointer">{row.tests.length} {t("tests", "项测试")}{row.tests.some((t) => t.outcome === "failed" || t.outcome === "error") ? t(" · failures", " · 存在失败") : ""}</summary><ul className="mt-1 space-y-1 break-all">{row.tests.map((t) => <li key={t.id} className={t.outcome === "failed" || t.outcome === "error" ? "font-semibold text-worse-900" : ""}>{t.id} ({displayText(t.outcome ?? "not run")})</li>)}</ul></details>}
                        </td>
                        <td className="py-2 pr-3 align-top">
                          <Badge tone={gap ? "caution" : row.result === "pass" ? "better" : row.result === "fail" ? "worse" : "neutral"}>
                            {gap && row.tests.length === 0 ? t("no test", "无测试") : displayText(row.result)}
                          </Badge>
                        </td>
                        <td className="py-2 align-top font-mono text-[11px] text-ink-500">
                          {row.evidence?.length ? row.evidence.map((e) => <div key={e.file}>{e.file && pkg.execution?.evidence_dir && packageFileUrl(`${pkg.execution.evidence_dir}/${e.file}`) ? <a className="text-accent-700 underline" href={packageFileUrl(`${pkg.execution.evidence_dir}/${e.file}`)} download>{e.file}</a> : e.file}{e.sha256 && <span title={e.sha256} className="block">sha256 {e.sha256.slice(0, 12)}…</span>}</div>) : "—"}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </section>

          <section className="card p-4" aria-label={t("Planted defects", "植入缺陷")} data-testid="defect-summary">
            <h2 className="card-title mb-2">{t("Planted defects", "植入缺陷")}</h2>
            {pkg.defects ? (
              <>
                <p className="text-sm text-ink-800">
                  {t("Detected", "已检出")} {pkg.defects.detected ?? t("unknown", "未知")} {t("of", "/")} {pkg.defects.planted ?? t("unknown", "未知")}.
                </p>
                {pkg.defects.historical && <p className="mt-1 text-sm font-semibold text-caution-900">{t("Historical experiment · not a result for the current code.", "历史实验 · 不代表当前代码的结果。")}</p>}
                {pkg.defects.head && <p className="mt-1 break-all font-mono text-xs text-ink-500">{t("Tested commit:", "测试提交：")} {pkg.defects.head}</p>}
                {pkg.defects.note && <p className="mt-1 text-xs text-ink-500">{pkg.defects.note}</p>}
                <ul className="mt-3 space-y-1 text-sm">
                  {(pkg.defects.rows ?? []).map((row) => (
                    <li key={row.id} className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-xs">{row.id}</span>
                      <Badge tone={row.detected ? "better" : "worse"}>{row.detected ? t("detected", "已检出") : t("missed", "未检出")}</Badge>
                      <span className="text-xs text-ink-500">{(row.stages ?? []).join(", ") || t("no stage", "无阶段")}</span>
                    </li>
                  ))}
                </ul>
              </>
            ) : (
              <p className="text-sm text-ink-500">{t("No defect run is included in this package.", "此验证包未包含缺陷测试。")}</p>
            )}
          </section>

          <section className="card p-4" aria-label={t("Package audit snapshot", "验证包审计快照")}>
            <h2 className="card-title mb-2">{t("Audit chain at package generation", "生成验证包时的审计链")}</h2>
            <p className={pkg.audit_chain?.ok === false ? "text-sm font-semibold text-worse-900" : "text-sm"}>{pkg.audit_chain?.ok === true ? t(`Chain intact — ${pkg.audit_chain.checked ?? "unknown"} entries`, `哈希链完整 — ${pkg.audit_chain.checked ?? "未知"} 条记录`) : pkg.audit_chain?.ok === false ? t(`Broken at seq ${pkg.audit_chain.first_bad_seq ?? "unknown"}`, `序号 ${pkg.audit_chain.first_bad_seq ?? "未知"} 处断裂`) : t("Chain status unavailable", "哈希链状态不可用")}</p>
            <p className="mt-1 text-xs text-ink-500">{t("This is the recorded package snapshot. Verify the current chain on Audit.", "此处显示已记录的验证包快照。请在审计页面验证当前哈希链。")}</p>
            <p className="mt-2 text-xs text-ink-500">{t("Human effort timing:", "人工耗时：")} {typeof pkg.effort?.manual_oq_5_requirements_minutes === "number" ? t(`${pkg.effort.manual_oq_5_requirements_minutes} min`, `${pkg.effort.manual_oq_5_requirements_minutes} 分钟`) : t("not measured", "未测量")}</p>
          </section>

          <section className="card p-4" aria-label={t("Summary report", "总结报告")}>
            <h2 className="card-title mb-2">{t("Summary report", "总结报告")}</h2>
            <p className="text-sm text-ink-800">
              {t("QA sign-off:", "质量保证签署：")} <span className="font-semibold">{displayText(pkg.report?.status ?? "not generated")}</span>
            </p>
            {pkg.report?.record_id && <p className="mt-1 font-mono text-xs text-ink-500">{pkg.report.record_id}</p>}
            {pkg.report?.reason && <p className="mt-1 text-sm text-ink-600">{pkg.report.reason}</p>}
          </section>
        </>
      )}
    </div>
  );
}

function Execution({ pkg }: { pkg: ValidationPackage }) {
  const t = useTranslation();
  const [files, setFiles] = useState<EvidenceFile[]>([]);
  const [error, setError] = useState<string | null>(null);
  const dir = pkg.execution?.evidence_dir;
  useEffect(() => {
    let cancelled = false;
    setFiles([]);
    setError(null);
    if (dir) void evidenceManifest(dir).then((m) => { if (!cancelled) setFiles(m.files); }).catch((err: unknown) => { if (!cancelled) setError(err instanceof Error ? err.message : String(err)); });
    return () => { cancelled = true; };
  }, [dir, pkg.generated_at]);
  const run = pkg.execution;
  return <section className="card space-y-2 p-4" aria-label={t("Executed evidence", "执行证据")} data-testid="execution-summary">
    <h2 className="card-title">{t("Executed evidence", "执行证据")}</h2>
    {!run ? <p className="text-sm text-ink-500">{t("No execution included.", "未包含执行记录。")}</p> : <>
      <p className="text-sm">{run.run_id} · {run.executor_name} · {run.finished_at ? formatUtc(run.finished_at) : t("time unavailable", "时间不可用")}</p>
      <p className="break-all font-mono text-xs text-ink-500">{t("Tested commit:", "测试提交：")} {run.git?.commit ?? t("unknown", "未知")}</p>
      <p className="text-sm font-semibold">{Object.entries(run.counts ?? {}).map(([k, v]) => `${displayText(k)} ${v}`).join(" · ")}</p>
      <p className="text-sm">{t("Recorded evidence integrity:", "已记录证据的完整性：")} {run.integrity_problems ? run.integrity_problems.length ? run.integrity_problems.join("; ") : t("all files matched at package generation", "生成验证包时所有文件均匹配") : t("not reported", "未报告")}</p>
      {run.executed_signature?.manifestation && <p className="text-xs text-ink-600">{run.executed_signature.manifestation}</p>}
      {dir && <a className="inline-block text-sm font-semibold text-accent-700" href={packageFileUrl(`${dir}/evidence_manifest.json`)} download>{t("Download evidence manifest", "下载证据清单")}</a>}
      {error && <p role="alert" className="text-sm text-worse-900">{t("Could not load evidence attachments:", "无法加载证据附件：")} {localizeCopy(error)}</p>}
      <details data-testid="evidence-attachments"><summary className="cursor-pointer text-sm font-semibold">{t("Evidence files and attachments (", "证据文件与附件（")}{files.length})</summary><ul className="mt-2 max-h-80 space-y-2 overflow-auto text-xs">{files.map((f) => <li key={f.path} className="break-all"><a className="font-semibold text-accent-700 underline" href={packageFileUrl(`${dir}/${f.path}`)} download>{f.path}</a><span className="block font-mono text-ink-500">{f.bytes ?? t("unknown", "未知")} {t("bytes · sha256", "字节 · sha256")} {f.sha256 ?? t("unknown", "未知")}</span></li>)}</ul></details>
    </>}
  </section>;
}

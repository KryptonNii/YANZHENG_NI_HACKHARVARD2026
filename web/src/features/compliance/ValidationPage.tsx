import { useEffect, useState } from "react";
import { formatUtc } from "@/app/format";
import { Badge, DraftStamp, EmptyState, ErrorPanel, Spinner } from "@/app/ui";
import { ApiError, evidenceManifest, packageFileUrl, validationPackage, type EvidenceFile, type PackageDeliverable, type ValidationPackage } from "./api";

function deliverableStatus(d: PackageDeliverable) {
  if (d.approval && d.status === "approved" && !d.approval.approved) return d.approval.status ?? "approval unconfirmed";
  return d.status;
}

function deliverableTone(status: string) {
  const s = status.toLowerCase();
  if (s === "approved" || s === "executed") return "better" as const;
  if (s.includes("draft") || s.includes("await")) return "caution" as const;
  if (s === "missing") return "worse" as const;
  return "neutral" as const;
}

export function ValidationPage() {
  const [pkg, setPkg] = useState<ValidationPackage | null>(null);
  const [missing, setMissing] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const load = async () => {
    setError(null);
    setMissing(null);
    try {
      setPkg(await validationPackage());
    } catch (err) {
      setPkg(null);
      if (err instanceof ApiError && err.code === "package_not_built") {
        setMissing(err.message);
        return;
      }
      setError(err instanceof ApiError ? err.message : err instanceof Error ? err.message : String(err));
    }
  };

  useEffect(() => {
    void load();
  }, []);

  const untested = pkg?.trace?.flags?.untested_requirements ?? [];

  return (
    <div className="space-y-4" data-testid="validation-page">
      <header className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <h1 className="text-2xl font-semibold tracking-tight">Validation package</h1>
          <p className="mt-1 text-sm text-ink-500">
            {pkg?.generated_at ? `Generated ${formatUtc(pkg.generated_at)}` : "Generated by tpv package"}
          </p>
        </div>
        <div className="flex items-center gap-2">
          <button type="button" className="btn-secondary" onClick={() => void load()}>Refresh package</button>
          {pkg?.draft_stamp && (
            <span data-testid="draft-stamp"><DraftStamp>{pkg.draft_stamp}</DraftStamp></span>
          )}
        </div>
      </header>

      {error && <ErrorPanel title="Couldn't load the validation package" message={error} onRetry={() => void load()} />}
      {missing && (
        <EmptyState title="No validation package yet">
          {missing}
        </EmptyState>
      )}
      {!pkg && !missing && !error && <Spinner label="Loading validation package" />}

      {pkg && (
        <>
          <section className="card space-y-2 p-4" aria-label="Package provenance">
            <p className="text-sm">{pkg.system ?? "Validation package"}</p>
            <p className="break-all font-mono text-xs text-ink-500">Package commit: {pkg.git?.commit ?? "unknown"}{pkg.git?.dirty ? " · uncommitted changes" : ""}</p>
            <div className="flex flex-wrap gap-3 text-sm font-semibold text-accent-700">
              <a href={packageFileUrl("index.html")} target="_blank" rel="noreferrer">Open package HTML</a>
              <a href={packageFileUrl("package_manifest.json")} download>Download package manifest</a>
            </div>
          </section>
          <Execution pkg={pkg} />
          <section className="card p-4" aria-label="Deliverables">
            <h2 className="card-title mb-3">Deliverables</h2>
            <ul className="divide-y divide-ink-100">
              {pkg.deliverables.map((d) => (
                <li key={d.id} className="flex flex-wrap items-center justify-between gap-2 py-2">
                  <div>
                    <p className="text-sm font-semibold text-ink-900">
                      <span className="mr-2 font-mono text-xs text-ink-400">{d.id}</span>
                      {d.title}
                    </p>
                    {d.sha256 && <p title={d.sha256} className="font-mono text-[11px] text-ink-400">Markdown sha256 {d.sha256.slice(0, 16)}…</p>}
                    {d.approval?.reason && <p className="text-xs text-ink-500">Approval: {d.approval.status} · {d.approval.reason}</p>}
                  </div>
                  <div className="flex items-center gap-2">
                    {d.draft_stamp ? <DraftStamp /> : null}
                    <Badge tone={deliverableTone(deliverableStatus(d))}>{deliverableStatus(d)}</Badge>
                    {packageFileUrl(d.html) && <a className="text-sm font-semibold text-accent-700" href={packageFileUrl(d.html)} target="_blank" rel="noreferrer" aria-label={`Open ${d.title} HTML`}>Open HTML</a>}
                    {packageFileUrl(d.md) && <a className="text-sm font-semibold text-accent-700" href={packageFileUrl(d.md)} download aria-label={`Download ${d.title} Markdown`}>Download Markdown</a>}
                  </div>
                </li>
              ))}
            </ul>
          </section>

          <section className="card p-4" aria-label="Traceability matrix">
            <h2 className="card-title mb-3">Traceability</h2>
            {untested.length > 0 && (
              <p data-testid="untested-requirements" className="mb-3 rounded-md border border-caution-300 bg-caution-50 px-3 py-2 text-sm font-medium text-caution-900">
                Untested requirements: {untested.join(", ")}
              </p>
            )}
            {!!pkg.trace?.flags?.failing_requirements?.length && <p data-testid="failing-requirements" className="mb-3 text-sm font-semibold text-worse-900">Failing requirements: {pkg.trace.flags.failing_requirements.join(", ")}</p>}
            {pkg.trace?.flags?.tests_without_requirement_count != null && <p className="mb-2 text-xs text-ink-500">Tests without requirement tags: {pkg.trace.flags.tests_without_requirement_count}</p>}
            {pkg.trace?.summary && (
              <p className="mb-3 text-xs text-ink-500">
                {Object.entries(pkg.trace.summary)
                  .map(([k, v]) => `${k} ${v}`)
                  .join(" · ")}
              </p>
            )}
            <div className="max-h-[28rem] overflow-auto">
              <table className="w-full text-left text-sm">
                <thead className="sticky top-0 bg-white text-xs uppercase tracking-wide text-ink-500">
                  <tr>
                    <th className="py-2 pr-3">Requirement</th>
                    <th className="py-2 pr-3">Tests</th>
                    <th className="py-2 pr-3">Result</th>
                    <th className="py-2">Evidence</th>
                  </tr>
                </thead>
                <tbody>
                  {(pkg.trace?.rows ?? []).map((row) => {
                    const gap = untested.includes(row.id) || row.tests.length === 0;
                    return (
                      <tr key={row.id} className={`border-t border-ink-100 ${gap ? "bg-caution-50" : ""}`} data-testid={`trace-${row.id}`}>
                        <td className="py-2 pr-3 align-top">
                          <span className="font-semibold">{row.id}</span>
                          <span className="mt-0.5 block text-xs text-ink-600">{row.text}</span>
                          <span className="text-xs text-ink-500">{row.risk ? `Risk ${row.risk}` : ""}{row.gxp != null ? ` · GxP ${row.gxp ? "yes" : "no"}` : ""}</span>
                        </td>
                        <td className="py-2 pr-3 align-top text-xs">
                          {row.tests.length === 0 ? "—" : <details><summary className="cursor-pointer">{row.tests.length} tests{row.tests.some((t) => t.outcome === "failed" || t.outcome === "error") ? " · failures" : ""}</summary><ul className="mt-1 space-y-1 break-all">{row.tests.map((t) => <li key={t.id} className={t.outcome === "failed" || t.outcome === "error" ? "font-semibold text-worse-900" : ""}>{t.id} ({t.outcome ?? "not run"})</li>)}</ul></details>}
                        </td>
                        <td className="py-2 pr-3 align-top">
                          <Badge tone={gap ? "caution" : row.result === "pass" ? "better" : row.result === "fail" ? "worse" : "neutral"}>
                            {gap && row.tests.length === 0 ? "no test" : row.result}
                          </Badge>
                        </td>
                        <td className="py-2 align-top font-mono text-[11px] text-ink-500">
                          {row.evidence?.length ? row.evidence.map((e) => <div key={e.file}>{e.file && pkg.execution?.evidence_dir && packageFileUrl(`${pkg.execution.evidence_dir}/${e.file}`) ? <a className="text-accent-700 underline" href={packageFileUrl(`${pkg.execution.evidence_dir}/${e.file}`)} download>{e.file}</a> : e.file}{e.sha256 && <span title={e.sha256} className="block">sha256 {e.sha256.slice(0, 12)}…</span>}</div>) : "—"}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </section>

          <section className="card p-4" aria-label="Planted defects" data-testid="defect-summary">
            <h2 className="card-title mb-2">Planted defects</h2>
            {pkg.defects ? (
              <>
                <p className="text-sm text-ink-800">
                  Detected {pkg.defects.detected ?? "unknown"} of {pkg.defects.planted ?? "unknown"}.
                </p>
                {pkg.defects.historical && <p className="mt-1 text-sm font-semibold text-caution-900">Historical experiment · not a result for the current code.</p>}
                {pkg.defects.head && <p className="mt-1 break-all font-mono text-xs text-ink-500">Tested commit: {pkg.defects.head}</p>}
                {pkg.defects.note && <p className="mt-1 text-xs text-ink-500">{pkg.defects.note}</p>}
                <ul className="mt-3 space-y-1 text-sm">
                  {(pkg.defects.rows ?? []).map((row) => (
                    <li key={row.id} className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-xs">{row.id}</span>
                      <Badge tone={row.detected ? "better" : "worse"}>{row.detected ? "detected" : "missed"}</Badge>
                      <span className="text-xs text-ink-500">{(row.stages ?? []).join(", ") || "no stage"}</span>
                    </li>
                  ))}
                </ul>
              </>
            ) : (
              <p className="text-sm text-ink-500">No defect run is included in this package.</p>
            )}
          </section>

          <section className="card p-4" aria-label="Package audit snapshot">
            <h2 className="card-title mb-2">Audit chain at package generation</h2>
            <p className={pkg.audit_chain?.ok === false ? "text-sm font-semibold text-worse-900" : "text-sm"}>{pkg.audit_chain?.ok === true ? `Chain intact — ${pkg.audit_chain.checked ?? "unknown"} entries` : pkg.audit_chain?.ok === false ? `Broken at seq ${pkg.audit_chain.first_bad_seq ?? "unknown"}` : "Chain status unavailable"}</p>
            <p className="mt-1 text-xs text-ink-500">This is the recorded package snapshot. Verify the current chain on Audit.</p>
            <p className="mt-2 text-xs text-ink-500">Human effort timing: {typeof pkg.effort?.manual_oq_5_requirements_minutes === "number" ? `${pkg.effort.manual_oq_5_requirements_minutes} min` : "not measured"}</p>
          </section>

          <section className="card p-4" aria-label="Summary report">
            <h2 className="card-title mb-2">Summary report</h2>
            <p className="text-sm text-ink-800">
              QA sign-off: <span className="font-semibold">{pkg.report?.status ?? "not generated"}</span>
            </p>
            {pkg.report?.record_id && <p className="mt-1 font-mono text-xs text-ink-500">{pkg.report.record_id}</p>}
            {pkg.report?.reason && <p className="mt-1 text-sm text-ink-600">{pkg.report.reason}</p>}
          </section>
        </>
      )}
    </div>
  );
}

function Execution({ pkg }: { pkg: ValidationPackage }) {
  const [files, setFiles] = useState<EvidenceFile[]>([]);
  const [error, setError] = useState<string | null>(null);
  const dir = pkg.execution?.evidence_dir;
  useEffect(() => {
    let cancelled = false;
    setFiles([]);
    setError(null);
    if (dir) void evidenceManifest(dir).then((m) => { if (!cancelled) setFiles(m.files); }).catch((err: unknown) => { if (!cancelled) setError(err instanceof Error ? err.message : String(err)); });
    return () => { cancelled = true; };
  }, [dir, pkg.generated_at]);
  const run = pkg.execution;
  return <section className="card space-y-2 p-4" aria-label="Executed evidence" data-testid="execution-summary">
    <h2 className="card-title">Executed evidence</h2>
    {!run ? <p className="text-sm text-ink-500">No execution included.</p> : <>
      <p className="text-sm">{run.run_id} · {run.executor_name} · {run.finished_at ? formatUtc(run.finished_at) : "time unavailable"}</p>
      <p className="break-all font-mono text-xs text-ink-500">Tested commit: {run.git?.commit ?? "unknown"}</p>
      <p className="text-sm font-semibold">{Object.entries(run.counts ?? {}).map(([k, v]) => `${k} ${v}`).join(" · ")}</p>
      <p className="text-sm">Recorded evidence integrity: {run.integrity_problems ? run.integrity_problems.length ? run.integrity_problems.join("; ") : "all files matched at package generation" : "not reported"}</p>
      {run.executed_signature?.manifestation && <p className="text-xs text-ink-600">{run.executed_signature.manifestation}</p>}
      {dir && <a className="inline-block text-sm font-semibold text-accent-700" href={packageFileUrl(`${dir}/evidence_manifest.json`)} download>Download evidence manifest</a>}
      {error && <p role="alert" className="text-sm text-worse-900">Could not load evidence attachments: {error}</p>}
      <details data-testid="evidence-attachments"><summary className="cursor-pointer text-sm font-semibold">Evidence files and attachments ({files.length})</summary><ul className="mt-2 max-h-80 space-y-2 overflow-auto text-xs">{files.map((f) => <li key={f.path} className="break-all"><a className="font-semibold text-accent-700 underline" href={packageFileUrl(`${dir}/${f.path}`)} download>{f.path}</a><span className="block font-mono text-ink-500">{f.bytes ?? "unknown"} bytes · sha256 {f.sha256 ?? "unknown"}</span></li>)}</ul></details>
    </>}
  </section>;
}

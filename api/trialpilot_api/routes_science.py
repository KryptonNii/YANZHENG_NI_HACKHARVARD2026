"""/api/science/results — serves A10's reproduction results JSON (static file, served as-is)."""

from __future__ import annotations

import json
from typing import Any

from fastapi import APIRouter, Depends

from .deps import services
from .errors import ApiError

router = APIRouter(prefix="/api/science", tags=["science"])


@router.get("/results")
def science_results(svc: Any = Depends(services)) -> Any:
    path = svc.settings.resolved_science_results
    if not path.is_file():
        raise ApiError(404, "science_results_missing",
                       "No science reproduction results yet. They are generated by A10's "
                       "science package into science/out/results.json.",
                       {"expected_path": str(path.relative_to(svc.settings.repo_root))
                        if path.is_relative_to(svc.settings.repo_root) else str(path)})
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ApiError(500, "science_results_invalid",
                       f"science results file is not valid JSON: {exc.msg}", {}) from exc
